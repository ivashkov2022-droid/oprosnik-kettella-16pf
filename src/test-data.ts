export function getQuestions(sex: Sex): Question[] {
  if (sex === "male") return maleQuestions;
  return maleQuestions.map((question) => {
    const override = femaleOverrides[question.id];
    return override ? { id: question.id, ...override } : question;
  });
}

function normKey(sex: Sex, ageGroup: AgeGroup) {
  return `${sex}_${ageGroup}`;
}

function rangeContains(range: string, value: number) {
  const [start, end = start] = range.split("-").map(Number);
  return value >= start && value <= end;
}

export function rawToSten(code: FactorCode, raw: number, sex: Sex, ageGroup: AgeGroup) {
  const ranges = norms[normKey(sex, ageGroup)][code];
  const direct = ranges.findIndex((range) => rangeContains(range, raw));
  if (direct >= 0) return direct + 1;

  let nearest = 1;
  let distance = Number.POSITIVE_INFINITY;
  ranges.forEach((range, index) => {
    const [start, end = start] = range.split("-").map(Number);
    const currentDistance = raw < start ? start - raw : raw > end ? raw - end : 0;
    if (currentDistance < distance) {
      distance = currentDistance;
      nearest = index + 1;
    }
  });
  return nearest;
}

